const AnySubject = Base.extend({ subjectType: z.enum(["PLOT", "CROP_CYCLE"]) });

// The backend merges `corrected` into the original event, validates the result
// against the original event's schema, and replays the subject's stream.
export const EventCorrected = AnySubject.extend({
  eventType: z.literal("EVENT_CORRECTED"),
  ...noQty,
  ...evidenceOptional,
  refEventId: Uuid,
  payload: z.object({
    reason: z.string().min(5).max(500),
    corrected: z.object({
      quantity: IntQty.nullable().optional(),
      occurredAt: IsoDateTime.optional(),
      evidenceHash: Sha256Hex.nullable().optional(),
      payload: z.record(z.string(), z.unknown()).optional(),
    }),
  }),
});

export const EventVoided = AnySubject.extend({
  eventType: z.literal("EVENT_VOIDED"),
  ...noQty,
  ...evidenceOptional,
  refEventId: Uuid,
  payload: z.object({ reason: z.string().min(5).max(500) }),
});

// What clients and the CSV import submit to POST /v1/events.
export const CanonicalEvent = z.discriminatedUnion("eventType", [
  PlotRegistered,
  SoilAnalysisAttached,
  CprIssued,
  FundingDisbursed,
  PlantingRecorded,
  InputApplicationRecorded,
  HarvestPlanned,
  HarvestStarted,
  TruckDispatched,
  TruckArrived,
  GrainReceived,
  CdaIssued,
  GrainReleased,
  SaleRecorded,
  InfoRequested,
  CprSettled,
  EventCorrected,
  EventVoided,
]);
export type CanonicalEvent = z.infer<typeof CanonicalEvent>;

// Fields the server adds on acceptance. recordHash covers event + meta.
export const RecordMeta = z.object({
  recordedAt: IsoDateTime,
  recordedBy: Uuid, // user who typed it (may be an admin acting for another org)
});

export const AnchorStatus = z.enum(["PENDING", "ANCHORED", "FAILED"]);
export const Anchor = z.object({
  status: AnchorStatus,
  recordHash: Sha256Hex,
  chainId: z.number().int().nullable(),
  txHash: z.string().regex(/^0x[0-9a-f]{64}$/).nullable(),
  blockNumber: z.number().int().nullable(),
  anchoredAt: IsoDateTime.nullable(),
});

export const StoredEvent = z.intersection(CanonicalEvent, RecordMeta);
export type StoredEvent = z.infer<typeof StoredEvent>;

export const EventRecord = z.intersection(
  StoredEvent,
  z.object({ anchor: Anchor, voided: z.boolean(), correctedBy: z.array(Uuid) }),
);
export type EventRecord = z.infer<typeof EventRecord>;
