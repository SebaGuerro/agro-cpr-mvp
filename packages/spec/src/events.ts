import { z } from "zod";

// Canonical event contract shared by backend, front-end and import.
// Frozen by Prompt 0: change only with the whole team's agreement.

export const ROLES = ["PRODUCER", "WAREHOUSE", "BUYER", "FINANCIER", "ADMIN"] as const;
export const Role = z.enum(ROLES);
export type Role = z.infer<typeof Role>;

export const EVENT_TYPES = [
  "PLOT_REGISTERED",
  "SOIL_ANALYSIS_ATTACHED",
  "CPR_ISSUED",
  "FUNDING_DISBURSED",
  "PLANTING_RECORDED",
  "INPUT_APPLICATION_RECORDED",
  "HARVEST_PLANNED",
  "HARVEST_STARTED",
  "TRUCK_DISPATCHED",
  "TRUCK_ARRIVED",
  "GRAIN_RECEIVED",
  "CDA_ISSUED",
  "GRAIN_RELEASED",
  "SALE_RECORDED",
  "INFO_REQUESTED",
  "CPR_SETTLED",
  "EVENT_CORRECTED",
  "EVENT_VOIDED",
] as const;
export type EventType = (typeof EVENT_TYPES)[number];

// uint16 codes used on-chain. Never renumber; append new types at the end.
export const EVENT_TYPE_CODES = Object.fromEntries(
  EVENT_TYPES.map((t, i) => [t, i + 1]),
) as Record<EventType, number>;

// Quantities are integers in base units. Sacas are display only (kg / 60).
export const UNITS = ["KG", "M2", "ML", "BRL_CENTS"] as const;
export const UNIT_CODES = { NONE: 0, KG: 1, M2: 2, ML: 3, BRL_CENTS: 4 } as const;
export const KG_PER_SACA = 60;

