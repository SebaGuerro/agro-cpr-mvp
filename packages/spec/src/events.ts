  HARVEST_PLANNED: ["PRODUCER", "ADMIN"],
  HARVEST_STARTED: ["PRODUCER", "ADMIN"],
  TRUCK_DISPATCHED: ["PRODUCER", "ADMIN"],
  TRUCK_ARRIVED: ["WAREHOUSE", "ADMIN"],
  GRAIN_RECEIVED: ["WAREHOUSE", "ADMIN"],
  CDA_ISSUED: ["WAREHOUSE", "ADMIN"],
  GRAIN_RELEASED: ["WAREHOUSE", "ADMIN"],
