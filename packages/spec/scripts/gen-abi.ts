import { readFileSync, writeFileSync } from "node:fs";

// Copies the AgroLedger ABI from the Foundry build into a typed module for viem.
// Run after `forge build` in contracts/.
const artifact = new URL("../../../contracts/out/AgroLedger.sol/AgroLedger.json", import.meta.url);
const { abi } = JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] };

const out = new URL("../src/agroLedgerAbi.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/gen-abi.ts from contracts/out. Do not edit.\nexport const agroLedgerAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out.pathname} (${abi.length} entries)`);
